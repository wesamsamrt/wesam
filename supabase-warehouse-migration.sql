-- ينشئ مخزنًا جديدًا ويضيف إليه نسخًا بكميات صفرية من أصناف مخزن مرجعي.
create or replace function public.add_warehouse(p_name text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    new_warehouse public.warehouses%rowtype;
    reference_warehouse text;
    insert_columns text;
    select_columns text;
begin
    if auth.uid() is null or not exists (select 1 from public.admins where id = auth.uid()) then
        raise exception 'غير مصرح لك بإضافة مخزن';
    end if;
    p_name := trim(p_name);
    if p_name is null or length(p_name) < 2 then raise exception 'اسم المخزن يجب أن يحتوي حرفين على الأقل'; end if;
    if length(p_name) > 60 then raise exception 'اسم المخزن طويل جدًا'; end if;

    insert into public.warehouses(name, created_by)
    values (p_name, auth.uid())
    returning * into new_warehouse;

    select name into reference_warehouse from public.warehouses where name <> p_name order by id limit 1;
    if reference_warehouse is not null then
        select
            string_agg(format('%I', column_name), ', ' order by ordinal_position),
            string_agg(case when column_name = 'quantity' then '0' else format('p.%I', column_name) end, ', ' order by ordinal_position)
        into insert_columns, select_columns
        from information_schema.columns
        where table_schema = 'public' and table_name = 'products'
          and column_name not in ('id', 'warehouse', 'copied_from_product_id', 'inventory_key')
          and is_generated = 'NEVER' and is_identity = 'NO';

        execute format(
            'insert into public.products (%s, warehouse, copied_from_product_id, inventory_key)
             select %s, $1, null, p.inventory_key
             from public.products p where p.warehouse = $2',
            insert_columns, select_columns
        ) using p_name, reference_warehouse;
    end if;

    return jsonb_build_object('id', new_warehouse.id, 'name', new_warehouse.name);
end;
$$;

-- تعيد هذه النسخة تعريف التحويلات بحيث تعمل مع أي مخزن جديد.
-- يعيد تعريف إنشاء التحويل ليعمل مع أي مخزن مضاف في جدول warehouses.
create or replace function public.create_warehouse_transfer(
    p_source_warehouse text,
    p_destination_warehouse text,
    p_notes text,
    p_items jsonb,
    p_creation_mode text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    new_transfer_id bigint;
    item jsonb;
    source_product public.products%rowtype;
    destination_product_id bigint;
    requested_quantity integer;
    product_label text;
begin
    if auth.uid() is null or not exists (select 1 from public.admins where id = auth.uid()) then raise exception 'غير مصرح لك بإنشاء تحويلات'; end if;
    if not exists (select 1 from public.warehouses where name = p_source_warehouse) or not exists (select 1 from public.warehouses where name = p_destination_warehouse) or p_source_warehouse = p_destination_warehouse then raise exception 'بيانات المخازن غير صالحة'; end if;
    if p_creation_mode not in ('request', 'send') then raise exception 'نوع التحويل غير صالح'; end if;
    if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'أضف منتجاً واحداً على الأقل للتحويل'; end if;

    insert into public.warehouse_transfers(source_warehouse, destination_warehouse, notes, created_by, status, requested_by_warehouse, requested_at)
    values (p_source_warehouse, p_destination_warehouse, nullif(trim(p_notes), ''), auth.uid(), case when p_creation_mode = 'request' then 'requested' else 'draft' end, case when p_creation_mode = 'request' then p_destination_warehouse else null end, case when p_creation_mode = 'request' then now() else null end)
    returning id into new_transfer_id;

    for item in select * from jsonb_array_elements(p_items) loop
        requested_quantity := (item->>'quantity')::integer;
        if requested_quantity is null or requested_quantity < 1 then raise exception 'كمية التحويل يجب أن تكون أكبر من صفر'; end if;
        select * into source_product from public.products where id = (item->>'product_id')::bigint and warehouse = p_source_warehouse;
        if not found then raise exception 'أحد منتجات التحويل غير موجود في المخزن المصدر'; end if;
        if source_product.quantity < requested_quantity then raise exception 'الكمية المطلوبة لمنتج % أكبر من المتاح', coalesce(source_product.model, source_product.product_code, source_product.id::text); end if;
        select id into destination_product_id from public.products where warehouse = p_destination_warehouse and inventory_key = source_product.inventory_key limit 1;
        if destination_product_id is null then raise exception 'لا توجد نسخة مطابقة للمنتج % في المخزن الوجهة', coalesce(source_product.model, source_product.product_code, source_product.id::text); end if;
        product_label := trim(concat_ws(' ', source_product.company, source_product.model, source_product.product_code));
        insert into public.warehouse_transfer_items(transfer_id, source_product_id, destination_product_id, product_name, quantity, product_code, company, model, color, product_type, type, image, price)
        values (new_transfer_id, source_product.id, destination_product_id, coalesce(nullif(product_label, ''), 'منتج #' || source_product.id), requested_quantity, source_product.product_code, source_product.company, source_product.model, source_product.color, source_product.product_type, source_product.type, source_product.image, source_product.price);
    end loop;
    return new_transfer_id;
end;
$$;

