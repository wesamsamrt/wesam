create or replace function public.save_team_account(p_email text, p_role text, p_permissions jsonb)
returns void
language plpgsql security definer set search_path = public, auth
as $$
declare
    target_user_id uuid;
    safe_permissions jsonb;
begin
    if auth.uid() is null or not exists (select 1 from public.team_accounts where user_id = auth.uid() and role = 'owner' and is_active) then
        raise exception 'غير مصرح لك بتعديل الصلاحيات';
    end if;
    if p_role not in ('owner', 'warehouse_manager', 'orders_staff', 'viewer') then
        raise exception 'الدور المختار غير صالح';
    end if;
    select id into target_user_id from auth.users where lower(email) = lower(trim(p_email)) limit 1;
    if target_user_id is null then
        raise exception 'لا يوجد حساب مسجل بهذا البريد. يجب أن يسجل المستخدم في الموقع أولًا.';
    end if;
    safe_permissions := jsonb_build_object(
        'warehouses', coalesce(p_permissions->'warehouses', '[]'::jsonb),
        'sections', coalesce(p_permissions->'sections', '[]'::jsonb)
    );
    insert into public.team_accounts(user_id, role, permissions, is_active, updated_by)
    values(target_user_id, p_role, safe_permissions, true, auth.uid())
    on conflict (user_id) do update set role = excluded.role, permissions = excluded.permissions, is_active = true, updated_at = now(), updated_by = auth.uid();
    insert into public.admins(id) values(target_user_id) on conflict do nothing;
    insert into public.team_account_audit(actor_id, target_user_id, action, details)
    values(auth.uid(), target_user_id, 'حفظ صلاحيات الحساب', jsonb_build_object('role', p_role, 'permissions', safe_permissions));
end;
$$;

create or replace function public.toggle_team_account(p_user_id uuid, p_is_active boolean)
returns void
language plpgsql security definer set search_path = public, auth
as $$
begin
    if auth.uid() is null or not exists (select 1 from public.team_accounts where user_id = auth.uid() and role = 'owner' and is_active) then
        raise exception 'غير مصرح لك بتعديل الحسابات';
    end if;
    if p_user_id = auth.uid() and not p_is_active then
        raise exception 'لا يمكنك إيقاف حسابك الحالي';
    end if;
    if not p_is_active and (select role from public.team_accounts where user_id = p_user_id) = 'owner' and (select count(*) from public.team_accounts where role = 'owner' and is_active) <= 1 then
        raise exception 'لا يمكن إيقاف آخر مدير عام';
    end if;
    update public.team_accounts set is_active = p_is_active, updated_at = now(), updated_by = auth.uid() where user_id = p_user_id;
    if not found then raise exception 'الحساب غير موجود'; end if;
    insert into public.team_account_audit(actor_id, target_user_id, action, details)
    values(auth.uid(), p_user_id, case when p_is_active then 'تفعيل الحساب' else 'إيقاف الحساب' end, jsonb_build_object('is_active', p_is_active));
end;
$$;

