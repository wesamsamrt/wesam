create table if not exists public.finance_accounts (
    id bigint generated by default as identity primary key,
    warehouse text not null,
    name text not null,
    account_type text not null check (account_type in ('cash','bank')),
    opening_balance numeric not null default 0,
    is_active boolean not null default true,
    notes text,
    created_at timestamptz not null default now(),
    created_by uuid default auth.uid()
);

create table if not exists public.finance_transactions (
    id bigint generated by default as identity primary key,
    warehouse text not null,
    account_id bigint not null references public.finance_accounts(id) on delete restrict,
    transaction_type text not null check (transaction_type in ('income','expense','transfer_in','transfer_out','opening')),
    amount numeric not null check (amount > 0),
    transaction_date date not null default current_date,
    reference_type text,
    reference_id bigint,
    counterparty text,
    notes text,
    created_at timestamptz not null default now(),
    created_by uuid default auth.uid()
);

create table if not exists public.finance_expense_categories (
    id bigint generated by default as identity primary key,
    warehouse text not null,
    name text not null,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    unique (warehouse, name)
);

create table if not exists public.finance_expenses (
    id bigint generated by default as identity primary key,
    warehouse text not null,
    account_id bigint not null references public.finance_accounts(id) on delete restrict,
    category_id bigint references public.finance_expense_categories(id) on delete set null,
    amount numeric not null check (amount > 0),
    expense_date date not null default current_date,
    payee text,
    notes text,
    attachment_url text,
    transaction_id bigint unique references public.finance_transactions(id) on delete set null,
    created_at timestamptz not null default now(),
    created_by uuid default auth.uid()
);

create table if not exists public.finance_suppliers (
    id bigint generated by default as identity primary key,
    warehouse text not null,
    name text not null,
    phone text,
    email text,
    address text,
    notes text,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    created_by uuid default auth.uid(),
    unique (warehouse, name)
);

create table if not exists public.finance_purchase_orders (
    id bigint generated by default as identity primary key,
    warehouse text not null,
    supplier_id bigint not null references public.finance_suppliers(id) on delete restrict,
    status text not null default 'مسودة' check (status in ('مسودة','مستحق','مدفوع جزئيًا','مدفوع','ملغي')),
    total numeric not null default 0,
    paid_amount numeric not null default 0,
    purchase_date date not null default current_date,
    due_date date,
    notes text,
    created_at timestamptz not null default now(),
    created_by uuid default auth.uid()
);

create table if not exists public.finance_supplier_payments (
    id bigint generated by default as identity primary key,
    warehouse text not null,
    purchase_order_id bigint not null references public.finance_purchase_orders(id) on delete cascade,
    account_id bigint not null references public.finance_accounts(id) on delete restrict,
    amount numeric not null check (amount > 0),
    payment_date date not null default current_date,
    notes text,
    transaction_id bigint unique references public.finance_transactions(id) on delete set null,
    created_at timestamptz not null default now(),
    created_by uuid default auth.uid()
);

create table if not exists public.finance_price_lists (
    id bigint generated by default as identity primary key,
    warehouse text not null,
    name text not null,
    price_mode text not null default 'fixed' check (price_mode in ('fixed','percentage')),
    adjustment numeric not null default 0,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    unique (warehouse, name)
);

create table if not exists public.finance_customer_payments (
    id bigint generated by default as identity primary key,
    warehouse text not null,
    customer_name text not null,
    account_id bigint not null references public.finance_accounts(id) on delete restrict,
    amount numeric not null check (amount > 0),
    payment_date date not null default current_date,
    notes text,
    transaction_id bigint unique references public.finance_transactions(id) on delete set null,
    created_at timestamptz not null default now(),
    created_by uuid default auth.uid()
);

create index if not exists finance_accounts_warehouse_idx on public.finance_accounts(warehouse);
create index if not exists finance_transactions_warehouse_date_idx on public.finance_transactions(warehouse, transaction_date desc);
create index if not exists finance_expenses_warehouse_date_idx on public.finance_expenses(warehouse, expense_date desc);
create index if not exists finance_suppliers_warehouse_idx on public.finance_suppliers(warehouse);
create index if not exists finance_purchase_orders_warehouse_idx on public.finance_purchase_orders(warehouse, purchase_date desc);

